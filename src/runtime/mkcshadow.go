// mkcshadow writes the shared checks of C's pointers against the shadow
// of its memory (cshadow.go) on linux/amd64: cshadow_amd64.s, their
// declarations in cshadow_amd64.go, and the table that the compiler
// picks them by, cmd/compile/internal/ssa/cshadowstubs.go.
//
// A check that ssa's cShadowSite would make in the compiled code (about
// fifteen instructions and sixty bytes at each site) is instead a call
// of one of these, five bytes. Each keeps every register: the pointer
// is in the one its name ends with and is there still on return. The
// flags say what the comparison in the compiled code would have: equal
// if the check is passed, not equal if the runtime is to see it.
//
// Run with "go run mkcshadow.go" in the runtime's directory.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
)

// What ssa's cheaders.go calls the checks (CSlowArith ...).
const (
	slowArith       = 0
	slowConv        = 1
	slowConvScalar  = 2
	slowConvUntyped = 3
	slowStoreByte   = 5
	slowStorePtr    = 6
)

// What the byte of a word in the shadow says (ssa's CShadowIn ...).
const (
	shIn     = 0x80
	shStart  = 0x40
	shRO     = 0x20
	shBase   = 46 // log2 of ssa's CShadowBase
	clScalar = 1
)

// The registers that a pointer may be in (AMD64Ops.go's gp).
var regs = []string{"AX", "CX", "DX", "BX", "BP", "SI", "DI", "R8", "R9", "R10", "R11", "R12", "R13", "R15"}

type shape struct {
	check, mask, size int64 // as in ssa.CSlowAux; size is the offset of an arithmetic
}

func (s shape) key() int64 { return s.check | s.mask<<8 | s.size<<16 }

func shapes() []shape {
	var r []shape
	for k := int64(-56); k <= 56; k += 8 {
		if k != 0 {
			r = append(r, shape{slowArith, 0, k})
		}
	}
	var sizes []int64
	for n := int64(1); n <= 16; n++ {
		sizes = append(sizes, n)
	}
	for n := int64(24); n <= 64; n += 8 {
		sizes = append(sizes, n)
	}
	for _, n := range sizes {
		r = append(r, shape{slowConvScalar, 0, n}, shape{slowConv, 0, n}, shape{slowStoreByte, 0, n})
		if n%8 == 0 {
			r = append(r, shape{slowConv, 7, n})
		}
	}
	r = append(r, shape{slowConvUntyped, 7, 8}, shape{slowStorePtr, 0, 8})
	return r
}

func each(x uint64, n int64) uint64 {
	var r uint64
	for i := int64(0); i < n; i++ {
		r |= x << (8 * i)
	}
	return r
}

// plan is what a shape's stub compares, as cShadowSite does.
type plan struct {
	high  uint64 // the bits of the pointer that are to be 0
	last  bool   // whether what begins in the last word looked at is to end there: size bytes from the pointer
	words int64  // the words that are looked at
	back  int64  // how many words before the pointer's they begin
	n     int64  // how many shadow bytes are loaded
	m, w  uint64 // under m they are to be w
}

func (s shape) plan() plan {
	p := plan{high: 0xFFFF_8000_0000_0000}
	words := (s.size + 7) / 8
	mask := s.mask
	switch s.check {
	case slowArith:
		k := s.size
		if k < 0 {
			n := -k / 8
			p.m = shIn | each(shStart, n)<<8
			p.w = shIn
			p.n = n + 1
		} else {
			n := k / 8
			p.m = each(shStart, n)<<8 | shIn<<(8*n)
			p.w = shIn << (8 * n)
			p.n = n + 1
			p.back = n
		}
		return p
	case slowConvScalar:
		p.n, p.m, p.w = words, each(shIn|3, words), each(shIn|clScalar, words)
	case slowConvUntyped:
		p.n, p.m, p.w = 1, shIn|3, shIn|2
	case slowConv:
		p.n, p.m, p.w = words, each(shIn, words), each(shIn, words)
	case slowStorePtr:
		mask = 7
		p.n, p.m, p.w = 1, shIn|shRO|3, shIn|2
	case slowStoreByte:
		p.n, p.m, p.w = words, each(shIn|shRO|2, words), each(shIn, words)
	}
	p.high |= uint64(mask)
	p.last = s.size > 1 && mask&7 != 7
	p.words = words
	return p
}

func main() {
	var s, c, g, t bytes.Buffer
	hdr := "// Code generated by mkcshadow.go; DO NOT EDIT.\n\n"
	s.WriteString(hdr + "#include \"textflag.h\"\n\n")
	g.WriteString(hdr + "package runtime\n\n")
	t.WriteString(hdr + "package ssa\n\n// cShadowStubs is the number of each check that runtime/cshadow_amd64.s\n// has a stub for, by its CSlowAux.\nvar cShadowStubs = map[int64]int{\n")

	consts := map[uint64]string{}
	constant := func(x uint64) string {
		if name, ok := consts[x]; ok {
			return name
		}
		name := fmt.Sprintf("runtime·cchkc%d", len(consts))
		consts[x] = name
		fmt.Fprintf(&c, "DATA %s+0(SB)/8, $0x%x\nGLOBL %s(SB), RODATA|NOPTR, $8\n", name, x, name)
		return name
	}

	for id, sh := range shapes() {
		p := sh.plan()
		fmt.Fprintf(&t, "\t%d: %d,\n", sh.key(), id)
		hi := constant(p.high)
		var load, op string
		switch {
		case p.n > 4:
			load, op = "MOVQ", "Q"
		case p.n > 2:
			load, op = "MOVL", "L"
		case p.n > 1:
			load, op = "MOVWLZX", "L"
		default:
			load, op = "MOVBLZX", "L"
		}
		for _, r := range regs {
			name := fmt.Sprintf("cchk%d_%s", id, r)
			fmt.Fprintf(&g, "func %s()\n", name)
			fmt.Fprintf(&s, "\n// %+v\nTEXT runtime·%s<ABIInternal>(SB),NOSPLIT|NOFRAME,$0-0\n", sh, name)
			fmt.Fprintf(&s, "\tTESTQ\t%s, %s(SB)\n\tJNE\tret\n\tPUSHQ\t%s\n", r, hi, r)
			if p.last {
				fmt.Fprintf(&s, "\tANDL\t$7, %s\n\tADDL\t$%d, %s\n\tSHRL\t$3, %s\n\tCMPL\t%s, $%d\n\tJNE\tpop\n\tMOVQ\t(SP), %s\n",
					r, sh.size-1, r, r, r, p.words-1, r)
			}
			fmt.Fprintf(&s, "\tSHRQ\t$3, %s\n\tBTSQ\t$%d, %s\n\t%s\t%d(%s), %s\n", r, shBase, r, load, -p.back, r, r)
			if op == "L" {
				fmt.Fprintf(&s, "\tANDL\t$0x%x, %s\n\tCMPL\t%s, $0x%x\n", uint32(p.m), r, r, uint32(p.w))
			} else {
				if p.m < 1<<31 {
					fmt.Fprintf(&s, "\tANDQ\t$0x%x, %s\n", p.m, r)
				} else {
					fmt.Fprintf(&s, "\tANDQ\t%s(SB), %s\n", constant(p.m), r)
				}
				if p.w < 1<<31 {
					fmt.Fprintf(&s, "\tCMPQ\t%s, $0x%x\n", r, p.w)
				} else {
					fmt.Fprintf(&s, "\tCMPQ\t%s, %s(SB)\n", r, constant(p.w))
				}
			}
			s.WriteString("pop:\n\tPOPQ\t" + r + "\nret:\n\tRET\n")
		}
	}
	t.WriteString("}\n")
	write := func(file string, b []byte, gofmt bool) {
		if gofmt {
			var err error
			if b, err = format.Source(b); err != nil {
				log.Fatal(file, ": ", err)
			}
		}
		if err := os.WriteFile(file, b, 0o666); err != nil {
			log.Fatal(err)
		}
	}
	s.WriteString("\n")
	s.Write(c.Bytes())
	write("cshadow_amd64.s", s.Bytes(), false)
	write("cshadow_amd64.go", g.Bytes(), true)
	write("../cmd/compile/internal/ssa/cshadowstubs.go", t.Bytes(), true)
}
