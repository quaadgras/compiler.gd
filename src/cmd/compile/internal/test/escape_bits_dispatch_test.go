// Escape-bits soundness through the less common ways a dynamic callee
// comes to exist: functions and itabs made by reflect, method and
// generic function values, and chains of trivial forwarders whose
// masks are resolved by synthesised compute fns
// (doc/gd/escape-bits.md Phase F3/F4). Each callee retains its
// argument, which the caller declared on its stack.

type ebdKeeper interface{ Keep(*ebaT) }

type ebdRetainer struct{ n int }

func (ebdRetainer) Keep(p *ebaT)   { ebaSink = p }
func (*ebdRetainer) KeepP(p *ebaT) { ebaSink = p }

type ebdNop struct{}

func (ebdNop) Keep(*ebaT) {}

type ebdFwd struct{ inner ebdKeeper }

func (f ebdFwd) Keep(p *ebaT) { f.inner.Keep(p) }

type ebdPFwd struct{ inner ebdKeeper }

func (f *ebdPFwd) Keep(p *ebaT) { f.inner.Keep(p) }

type ebdEmbed struct{ ebdKeeper }

func ebdKeepG[P any](p *P) { ebaSink = any(p).(*ebaT) }

var (
	ebdFn func(*ebaT)
	ebdK  ebdKeeper
)

//go:noinline
func ebdCallFn() {
	var x ebaT
	x.a = 42
	ebdFn(&x)
}

//go:noinline
func ebdCallK() {
	var x ebaT
	x.a = 42
	ebdK.Keep(&x)
}

func ebdChain(n int, bottom ebdKeeper) ebdKeeper {
	k := bottom
	for i := range n {
		switch i % 3 {
		case 0:
			k = ebdFwd{k}
		case 1:
			k = &ebdPFwd{k}
		default:
			k = ebdEmbed{k}
		}
	}
	return k
}

func TestEscapeBitsReflectFuncValues(t *testing.T) {
	ft := reflect.TypeOf(ebdFn)
	var r ebdRetainer
	for _, c := range []struct {
		name string
		fn   func(*ebaT)
	}{
		{"MakeFunc", reflect.MakeFunc(ft, func(args []reflect.Value) []reflect.Value {
			ebaSink = args[0].Interface().(*ebaT)
			return nil
		}).Interface().(func(*ebaT))},
		{"reflect method value", reflect.ValueOf(ebdRetainer{}).Method(0).Interface().(func(*ebaT))},
		{"reflect generic func", reflect.ValueOf(ebdKeepG[ebaT]).Interface().(func(*ebaT))},
		{"generic func", ebdKeepG[ebaT]},
		{"method value", ebdRetainer{}.Keep},
		{"pointer method value", r.KeepP},
	} {
		t.Run(c.name, func(t *testing.T) {
			ebaSink = nil
			ebdFn = c.fn
			ebdCallFn()
			ebaCheckSink(t, 42)
		})
	}
}

func TestEscapeBitsRuntimeItabs(t *testing.T) {
	st := reflect.StructOf([]reflect.StructField{{Name: "R", Type: reflect.TypeOf(ebdRetainer{}), Anonymous: true}})
	var fromAny any = ebdRetainer{}
	for _, c := range []struct {
		name string
		k    ebdKeeper
	}{
		{"reflect value", reflect.New(reflect.TypeOf(ebdRetainer{})).Elem().Interface().(ebdKeeper)},
		{"StructOf promoted method", reflect.New(st).Elem().Interface().(ebdKeeper)},
		{"type assertion", fromAny.(ebdKeeper)},
	} {
		t.Run(c.name, func(t *testing.T) {
			ebaSink = nil
			ebdK = c.k
			ebdCallK()
			ebaCheckSink(t, 42)
		})
	}
}

// TestEscapeBitsForwarderChains nests forwarders of every kind; the
// mask of each level is resolved through the next level's receiver,
// and beyond the depth limit the mask falls back to all-escape.
func TestEscapeBitsForwarderChains(t *testing.T) {
	for _, n := range []int{1, 2, 3, 7, 8, 9, 20} {
		t.Run(fmt.Sprint(n), func(t *testing.T) {
			ebaSink = nil
			ebdK = ebdChain(n, ebdRetainer{})
			ebdCallK()
			ebaCheckSink(t, 42)
		})
	}
}

func TestEscapeBitsForwarderInnerChanged(t *testing.T) {
	w := &ebdPFwd{ebdNop{}}
	ebdK = w
	ebdCallK()
	ebaSink = nil
	w.inner = ebdFwd{ebdRetainer{}}
	ebdCallK()
	ebaCheckSink(t, 42)
}

// TestEscapeBitsForwarderChainNonEscape: a short chain of forwarders,
// including the autogenerated wrappers of methods promoted from an
// embedded interface, ending in a callee that doesn't retain its
// argument keeps it on the stack.
func TestEscapeBitsForwarderChainNonEscape(t *testing.T) {
	for _, c := range []struct {
		name string
		k    ebdKeeper
	}{
		{"value", ebdFwd{ebdNop{}}},
		{"pointer", &ebdPFwd{ebdNop{}}},
		{"embedded", ebdEmbed{ebdNop{}}},
		{"pointer to embedded", &ebdEmbed{ebdNop{}}},
		{"mixed chain", ebdChain(5, ebdNop{})},
	} {
		ebdK = c.k
		if n := testing.AllocsPerRun(100, ebdCallK); n != 0 {
			t.Errorf("%s: got %v allocs through a non-retaining forwarder chain, want 0", c.name, n)
		}
	}
}

func TestEscapeBitsEmbeddedNilInner(t *testing.T) {
	ebdK = ebdEmbed{}
	defer func() {
		if recover() == nil {
			t.Fatal("call through a nil embedded interface did not panic")
		}
	}()
	ebdCallK()
}
