package base

import (
	"cmd/internal/obj"
	"cmd/internal/src"
	"sync"
)

type Invocation struct {
	atExitFuncs []func()

	Timer Timings

	// Debug holds the parsed debugging configuration values.
	Debug DebugFlags

	// DebugSSA is called to set a -d ssa/... option.
	// If nil, those options are reported as invalid options.
	// If DebugSSA returns a non-empty string, that text is reported as a compiler error.
	DebugSSA func(phase, flag string, val int, valString string) string

	Ctxt *obj.Link

	// Pos is the current source position being processed,
	// printed by Errorf, ErrorfLang, Fatalf, and Warnf.
	Pos src.XPos

	AutogeneratedPos src.XPos

	// Flag holds the parsed command-line flags.
	// See ParseFlag for non-zero defaults.
	Flag CmdFlags

	errorMsgs       []errorMsg
	numErrors       int // number of entries in errorMsgs that are errors (as opposed to warnings)
	numSyntaxErrors int

	// lasterror keeps track of the most recently issued error,
	// to avoid printing multiple error messages on the same line.
	lasterror struct {
		syntax src.XPos // source position of last syntax error
		other  src.XPos // source position of last non-syntax error
		msg    string   // error message of last non-syntax error
	}

	CurFunc any // *ir.Func
	Package any //*ir.Package

	LocalPkg any // *types.Pkg

	Status int

	// Per-compile counters used to mint unique synthesised names.
	// Were package-level globals; threaded here so multiple compile
	// invocations in one process don't share name spaces.
	Renameinitgen     int   // noder/noder.go (renameinit name minter)
	NoderInlgen       int   // noder/reader.go (inlined-call name minter)
	Dnamecount        int   // reflectdata/reflect.go (dname name minter)
	Slicedatagen      int   // staticdata/data.go (sliceData name minter)
	Statuniqgen       int   // staticinit/sched.go (static temp name minter)
	Mapinitgen        int   // staticinit/sched.go (map-init name minter)
	TypeAssertGen     int   // walk/expr.go (type-assert helper minter)
	InterfaceSwitchGen int  // walk/switch.go (iface-switch helper minter)
	GlobClosgen       int32 // ir/func.go (closure name minter)

	// Per-compile noder reader maps. Type-asserted at use site to
	// avoid an import cycle (noder imports base, not the other
	// direction). Were package-level globals; same per-Invocation
	// rationale as the counters above.
	NoderObjReader        any // map[*types.Sym]noder.pkgReaderIndex
	NoderBodyReader       any // map[*ir.Func]noder.pkgReaderIndex
	NoderImportBodyReader any // map[*types.Sym]noder.pkgReaderIndex
	NoderTodoBodies       any // []*ir.Func — pending function bodies during readBodies
	NoderTodoDicts        any // []func()    — pending dictionary constructors during readBodies

	// Per-compile escape caches.
	EscapeSynthRegistered any // map[string]*ir.Func — F4 forwarder compute-fn registry

	// Per-compile staticinit map-init bookkeeping. Stored on
	// Invocation so AddKeepRelocations / dwarfgen lookups don't
	// rely on package-level globals.
	StaticinitVarToMapInit any // map[*ir.Name]*ir.Func
	StaticinitMapInitToVar any // map[*ir.Func]*ir.Name

	// Per-function walk caches. Set on entry to walk.Walk, cleared
	// on exit (via defer). Stored on Invocation rather than as
	// package vars so concurrent compile invocations don't clobber
	// each other's transient walk state.
	WalkStaticValues any // map[ir.Node]ir.Node — findStaticValues result
	WalkEscapeBoxes  any // map[*ir.Name]*ir.Name — promoted-EscCandidate boxes

	// pkginit asan instrumentation tables — populated only under
	// -asan, deterministic-order via slice paired with the map.
	PkginitInstrumentGlobalsMap   any // map[string]ir.Node
	PkginitInstrumentGlobalsSlice any // []ir.Node

	// Largest size of an .L_zero buffer needed by reflectdata.ZeroAddr
	// during this compile. Emitted as a single DUPOK RODATA symbol at
	// finalize time.
	ReflectdataZeroSize int64

	// Per-compile noder wrapper-type bookkeeping. Drained by
	// MakeWrappers / wrapMethodValue at end of unified IR reading;
	// without per-Invocation storage two compiles would queue each
	// other's wrappers.
	NoderNeedWrapperTypes        any // []*types.Type
	NoderHaveWrapperTypes        any // []*types.Type
	NoderNeedMethodValueWrappers any // []noder.methodValueWrapper
	NoderHaveMethodValueWrappers any // []noder.methodValueWrapper

	// The pkgReader for the package currently being compiled.
	// Used by importedDef to distinguish local-package symbols
	// from imported ones; per-Invocation so two compiles can
	// each have their own local reader.
	NoderLocalPkgReader any // *noder.pkgReader

	// Set of LSyms for outlined map.init.NNN functions, used by
	// weakenGlobalMapInitRelocs to flag R_WEAK references between
	// init functions and their outlined map initializers.
	SsagenGlobalMapInitLsyms any // map[*obj.LSym]struct{}

	// nowritebarrierrec checker — set when -d=nowritebarrier… is on.
	// Per-compile so two parallel compiles don't share the call-graph
	// state.
	SsagenNowritebarrierrecCheck any // *ssagen.nowritebarrierrecChecker

	// typecheck.DeclFunc / FinishFuncBody push and pop CurFunc onto
	// this stack. Per-compile because CurFunc itself is per-compile;
	// concurrent compiles would otherwise corrupt each other.
	TypecheckFuncStack any // []*ir.Func

	// staticdata.FuncSym: list of *ir.Name needing function-value
	// symbols, populated concurrently from the backend (mutex-
	// protected) and consumed by WriteFuncSyms at end of compile.
	StaticdataFuncsymsMu sync.Mutex
	StaticdataFuncsyms   any // []*ir.Name

	// gd compile loop: functions waiting to be backend-compiled.
	// Populated by enqueueFunc, drained by compileFunctions.
	GdCompileQueue any // []*ir.Func

	// reflectdata pending itab EscMask slots — populated by writeITab
	// while emitting itabs and consumed by FinalizeItabMasks after
	// escape analysis. Per-compile because each Invocation has its
	// own escape state and itab list.
	ReflectdataPendingItabMasks any // []reflectdata.pendingItabMask

	// reflectdata runtime-type-descriptor work queues. signatmu/gcsymmu
	// guard concurrent access from the parallel SSA backend; signatset
	// dedups, signatslice is the FIFO of types still needing emit, and
	// gcsymset tracks which types' GC bitmaps have already been
	// emitted.
	ReflectdataSignatMu    sync.Mutex
	ReflectdataSignatSet   any // map[*types.Type]struct{}
	ReflectdataSignatSlice any // []reflectdata.typeAndStr
	ReflectdataGcsymMu     sync.Mutex
	ReflectdataGcsymSet    any // map[*types.Type]struct{}

	// logopt diagnostic accumulator. The mutex guards concurrent
	// appends from the parallel SSA backend; the slice is sorted
	// by source position at FlushLoggedOpts time.
	LogoptMu         sync.Mutex
	LogoptLoggedOpts any // []*logopt.LoggedOpt
}
