// ccGenerated is the header that cmd/cc writes at the top of the Go it
// generates.
const ccGenerated = "// Code generated by cmd/cc from "

// importsC23AsGenerated reports whether every file of importer that
// imports internal/c23 is Go that cmd/cc generated (gd fork). Such files
// may import it from any package: it is the run-time support of C
// (doc/gd/cc.md), as runtime/cgo is cgo's, but no other code may.
func importsC23AsGenerated(importer *Package, path string) bool {
	if importer == nil || importer.Internal.Build == nil {
		return false
	}
	pos := importer.Internal.Build.ImportPos[path]
	if len(pos) == 0 {
		return false
	}
	for _, p := range pos {
		f, err := os.Open(p.Filename)
		if err != nil {
			return false
		}
		head := make([]byte, len(ccGenerated))
		n, _ := f.Read(head)
		f.Close()
		if !bytes.Equal(head[:n], []byte(ccGenerated)) {
			return false
		}
	}
	return true
}

// ccContext reports whether bp, loaded with cgo off, is a package that
// cmd/cc can build instead of cgo (gd fork, doc/gd/cc.md), and if so
// returns the context to load it again with: cgo on, so that its import
// "C" files and its files with a cgo build constraint are in, and those
// with !cgo out, as with cgo. It can if, loaded so, every preamble and C
// file uses no #cgo directive and includes only headers cmd/cc provides
// or the package's own, every name the Go uses as C.name is one cmd/cc
// defines (internal/testpty's posix_openpt is not), and it has no C++,
// Objective-C, Fortran or assembly for a C compiler.
func ccContext(bp *build.Package, err error) (build.Context, bool) {
	ctx := cfg.BuildContext
	var noGo *build.NoGoError
	if err != nil && !errors.As(err, &noGo) || ctx.CgoEnabled || bp == nil || len(bp.IgnoredGoFiles) == 0 {
		// A package whose only Go files import "C" has none with cgo off.
		return ctx, false
	}
	// GOWASM=gc without split has no addresses for C's pointers.
	if slices.Contains(ctx.ToolTags, "wasm.gc") && !slices.Contains(ctx.ToolTags, "wasm.split") {
		return ctx, false
	}
	// cmd/cc lays C out for 8-byte pointers and for wasm32
	// (ccmain/target.go), not for the other 32-bit targets, where
	// internal/c23 has no tag that faults either (tag_32.go).
	switch ctx.GOARCH {
	case "386", "arm", "mips", "mipsle":
		return ctx, false
	}
	ctx.CgoEnabled = true
	var cgoFiles []string
	for _, f := range bp.IgnoredGoFiles {
		if ok, _ := ctx.MatchFile(bp.Dir, f); !ok {
			continue
		}
		pre, imports := preamble(filepath.Join(bp.Dir, f))
		if !imports {
			continue
		}
		if !ccSource(pre) {
			return ctx, false
		}
		cgoFiles = append(cgoFiles, f)
	}
	if len(cgoFiles) == 0 {
		return ctx, false
	}
	for _, f := range append(bp.CXXFiles, append(bp.MFiles, append(bp.FFiles, bp.SFiles...)...)...) {
		if ok, _ := ctx.MatchFile(bp.Dir, f); ok {
			return ctx, false
		}
	}
	for _, f := range bp.CFiles {
		b, err := os.ReadFile(filepath.Join(bp.Dir, f))
		if err != nil || !ccSource(string(b)) {
			return ctx, false
		}
	}
	// An error is cmd/cc's to report when it builds the package.
	if missing, err := cchost.Undefined(bp.Dir, cgoFiles); err == nil && len(missing) > 0 {
		return ctx, false
	}
	return ctx, true
}

// preamble returns the cgo preambles of the Go file, and whether it
// imports "C".
func preamble(file string) (string, bool) {
	f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.ImportsOnly|parser.ParseComments)
	if err != nil {
		return "", false
	}
	var b strings.Builder
	imports := false
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.IMPORT {
			continue
		}
		for _, sp := range gd.Specs {
			is := sp.(*ast.ImportSpec)
			if is.Path.Value != `"C"` {
				continue
			}
			imports = true
			doc := is.Doc
			if doc == nil && len(gd.Specs) == 1 {
				doc = gd.Doc
			}
			if doc != nil {
				b.WriteString(doc.Text())
			}
		}
	}
	return b.String(), imports
}

// ccHeaders are the system headers cmd/cc provides.
var ccHeaders = func() map[string]bool {
	m := map[string]bool{}
	for _, h := range cchost.Headers() {
		m[h] = true
	}
	return m
}()

// ccSource reports whether C source uses no #cgo directive and includes
// only headers that cmd/cc provides or the package's own ("...").
func ccSource(src string) bool {
	for _, l := range strings.Split(src, "\n") {
		l = strings.TrimSpace(l)
		if !strings.HasPrefix(l, "#") {
			continue
		}
		d := strings.TrimSpace(l[1:])
		switch {
		case strings.HasPrefix(d, "cgo"):
			return false
		case strings.HasPrefix(d, "include"):
			h := strings.TrimSpace(d[len("include"):])
			if strings.HasPrefix(h, "<") && !ccHeaders[strings.TrimSuffix(h[1:], ">")] {
				return false
			}
		}
	}
	return true
}

// ccLibcPackages are internal/c23's packages of headers, which Go that
// cmd/cc generates may import besides internal/c23.
func ccLibcPackages() []string { return cchost.LibcPackages() }
