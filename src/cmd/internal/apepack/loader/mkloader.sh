# mkloader.sh builds the loaders with clang and lld into ../zloader.go:
#
# loader.c, for the ELF hosts, as one segment of code at an address no
# image of a GOOS=ape program is at (they are low, or from 4 GB up);
#
# loader_darwin.c, for darwin, as a Mach-O that imports what it uses
# of the system's library (libSystem.tbd says what that has: the loader
# is built without the system's SDK), with the signature lld gives it.

set -e
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

build() { # goarch triple maxpage
	clang --target=$2 -Os -ffreestanding -fno-builtin -fno-stack-protector -fpie \
		-fno-asynchronous-unwind-tables -fno-unwind-tables -fno-ident -Wall -Werror \
		-nostdlib -static -fuse-ld=lld \
		-Wl,--build-id=none,-z,norelro,-z,noseparate-code,-z,max-page-size=$3,-z,noexecstack \
		-Wl,--image-base=0xc0000000,-e,_start,--no-rosegment,-s \
		-o "$tmp/$1.elf" loader.c
	llvm-objcopy --strip-sections "$tmp/$1.elf" "$tmp/$1"
	# A FreeBSD program by its header; Linux does not look.
	printf '\011' | dd of="$tmp/$1" bs=1 seek=7 conv=notrunc 2>/dev/null
}
build amd64 x86_64-unknown-linux-gnu 4096
build arm64 aarch64-unknown-linux-gnu 65536

build_darwin() { # goarch triple arch [lld flags]
	g=$1 t=$2 a=$3
	shift 3
	clang --target=$t -Os -ffreestanding -fno-builtin -fno-stack-protector \
		-fno-asynchronous-unwind-tables -fno-unwind-tables -fno-ident -Wall -Werror \
		-c -o "$tmp/darwin-$g.o" loader_darwin.c
	ld64.lld -arch $a -platform_version macos 11.0 11.0 -dead_strip "$@" \
		-o "$tmp/darwin-$g" "$tmp/darwin-$g.o" libSystem.tbd
}
build_darwin arm64 arm64-apple-macos11 arm64
build_darwin amd64 x86_64-apple-macos11 x86_64

{
	echo "// Code generated by loader/mkloader.sh from loader/loader.c and loader/loader_darwin.c. DO NOT EDIT."
	echo
	echo "package apepack"
	echo
	echo "// loadersGz are the loaders, gzipped, by GOARCH (of the ELF hosts)"
	echo "// and darwin/GOARCH."
	echo "var loadersGz = map[string]string{"
	for a in amd64 arm64 darwin-amd64 darwin-arm64; do
		echo "	\"$(echo $a | tr - /)\": \"\" +"
		gzip -9n < "$tmp/$a" | od -An -v -tx1 -w24 | sed 's/ /\\x/g; s/^/		"/; s/$/" +/'
		echo "		\"\","
	done
	echo "}"
} > ../zloader.go
gofmt -l ../zloader.go
wc -c "$tmp/amd64" "$tmp/arm64" "$tmp/darwin-amd64" "$tmp/darwin-arm64"
