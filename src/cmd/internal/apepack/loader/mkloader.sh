# mkloader.sh builds loader.c with clang and lld into ../zloader.go.
# The loader is one segment of code at an address no image of a GOOS=ape
# program is at (they are low, or from 4 GB up).

set -e
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

build() { # goarch triple maxpage
	clang --target=$2 -Os -ffreestanding -fno-builtin -fno-stack-protector -fpie \
		-fno-asynchronous-unwind-tables -fno-unwind-tables -fno-ident -Wall -Werror \
		-nostdlib -static -fuse-ld=lld \
		-Wl,--build-id=none,-z,norelro,-z,noseparate-code,-z,max-page-size=$3,-z,noexecstack \
		-Wl,--image-base=0xc0000000,-e,_start,--no-rosegment,-s \
		-o "$tmp/$1.elf" loader.c
	llvm-objcopy --strip-sections "$tmp/$1.elf" "$tmp/$1"
	# A FreeBSD program by its header; Linux does not look.
	printf '\011' | dd of="$tmp/$1" bs=1 seek=7 conv=notrunc 2>/dev/null
}
build amd64 x86_64-unknown-linux-gnu 4096
build arm64 aarch64-unknown-linux-gnu 65536

{
	echo "// Code generated by loader/mkloader.sh from loader/loader.c. DO NOT EDIT."
	echo
	echo "package apepack"
	echo
	echo "// loaders are the loaders of the ELF hosts, by GOARCH."
	echo "var loaders = map[string]string{"
	for a in amd64 arm64; do
		echo "	\"$a\": \"\" +"
		od -An -v -tx1 -w24 "$tmp/$a" | sed 's/ /\\x/g; s/^/		"/; s/$/" +/'
		echo "		\"\","
	done
	echo "}"
} > ../zloader.go
gofmt -l ../zloader.go
wc -c "$tmp/amd64" "$tmp/arm64"
