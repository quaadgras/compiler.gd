const (
	notPortable      = " && !portable"
	notPortableAlone = "!portable && !portgen" // never "!portable", which people write
)

// setNotPortable adds "&& !portable" to the //go:build line of file, or removes it.
func setNotPortable(file string, want bool) error {
	src, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	loc := goBuildLine.FindIndex(src)
	var out []byte
	switch {
	case loc == nil && want:
		// Before the package clause's comments: after the copyright.
		i := bytes.Index(src, []byte("\n\n"))
		if i < 0 {
			return fmt.Errorf("%s: no place for a //go:build line", file)
		}
		out = slices.Concat(src[:i+2], []byte("//go:build "+notPortableAlone+"\n\n"), src[i+2:])
	case loc == nil:
		return nil
	default:
		line := strings.TrimSpace(string(src[loc[0]:loc[1]]))
		expr := strings.TrimPrefix(line, "//go:build ")
		has := strings.HasSuffix(expr, notPortable) || expr == notPortableAlone
		switch {
		case want == has:
			return nil
		case want:
			if strings.Contains(expr, "||") {
				expr = "(" + expr + ")"
			}
			expr += notPortable
		case expr == notPortableAlone:
			// Ours alone: remove the line and the blank line after it.
			end := loc[1]
			if end < len(src) && src[end] == '\n' {
				end++
			}
			return os.WriteFile(file, slices.Concat(src[:loc[0]], src[end:]), 0o666)
		default:
			expr = strings.TrimSuffix(expr, notPortable)
			if strings.HasPrefix(expr, "(") && strings.HasSuffix(expr, ")") && strings.Contains(expr, "||") {
				expr = expr[1 : len(expr)-1]
			}
		}
		out = slices.Concat(src[:loc[0]], []byte("//go:build "+expr+"\n"), src[loc[1]:])
	}
	return os.WriteFile(file, out, 0o666)
}

var goBuildLine = regexp.MustCompile(`(?m)^//go:build .*\n`)

// dropUnusedImports removes the imports a host copy no longer uses
// (their uses were declarations the portable file now makes).
func dropUnusedImports(src []byte) []byte {
	f, err := parser.ParseFile(token.NewFileSet(), "", src, parser.ParseComments|parser.ImportsOnly)
	if err != nil {
		return src
	}
	tf := token.NewFileSet()
	full, err := parser.ParseFile(tf, "", src, 0)
	if err != nil {
		return src
	}
	used := map[string]bool{}
	ast.Inspect(full, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			// (Not a local variable of the package's name.)
			if x, ok := sel.X.(*ast.Ident); ok && x.Obj == nil {
				used[x.Name] = true
			}
		}
		return true
	})
	var edits []edit
	ff := token.NewFileSet()
	f, _ = parser.ParseFile(ff, "", src, parser.ParseComments|parser.ImportsOnly)
	// (An import without parentheses goes whole.)
	whole := map[*ast.ImportSpec]*ast.GenDecl{}
	for _, d := range f.Decls {
		if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.IMPORT && !gd.Lparen.IsValid() && len(gd.Specs) == 1 {
			whole[gd.Specs[0].(*ast.ImportSpec)] = gd
		}
	}
	for _, imp := range f.Imports {
		path := strings.Trim(imp.Path.Value, `"`)
		name := filepath.Base(path)
		if len(name) >= 2 && name[0] == 'v' && strings.Trim(name[1:], "0123456789") == "" && strings.Contains(path, "/") {
			name = filepath.Base(filepath.Dir(path))
		}
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if name == "_" || name == "." || used[name] {
			continue
		}
		start, end := ff.Position(imp.Pos()).Offset, ff.Position(imp.End()).Offset
		if path == "unsafe" && bytes.Contains(src, []byte("//go:linkname")) {
			edits = append(edits, edit{start, end, `_ "unsafe"`})
			continue
		}
		if gd := whole[imp]; gd != nil {
			start, end = ff.Position(gd.Pos()).Offset, ff.Position(gd.End()).Offset
		}
		edits = append(edits, edit{start, end, ""})
	}
	return applyEdits(src, edits)
}

// fieldOwnerOf returns the named struct type that declares the field sel
// selects.
func fieldOwnerOf(sel *types.Selection) *types.Named {
	cur := sel.Recv()
	var owner *types.Named
	for _, idx := range sel.Index() {
		t := types.Unalias(cur)
		if p, ok := t.(*types.Pointer); ok {
			t = types.Unalias(p.Elem())
		}
		owner, _ = t.(*types.Named)
		st, ok := t.Underlying().(*types.Struct)
		if !ok {
			return nil
		}
		cur = st.Field(idx).Type()
	}
	return owner
}

// asmDefinesFunc reports whether hp's assembly defines ·name.
func (g *pkgGen) asmDefinesFunc(hp *hostPkg, name string) bool {
	for _, f := range hp.bp.SFiles {
		src, err := os.ReadFile(filepath.Join(g.dir, f))
		if err == nil && regexp.MustCompile(`TEXT\s+(?:runtime)?·`+regexp.QuoteMeta(name)+`\b`).Match(src) {
			return true
		}
	}
	return false
}

// viaHostEmbed returns, for a selection that goes through a shared
// struct's embedded pointer to a host type, the explicit path to that
// field (".file") and the host type's name; or "".
func (g *pkgGen) viaHostEmbed(hp *hostPkg, sel *types.Selection) (string, string) {
	cur := sel.Recv()
	path := ""
	for _, idx := range sel.Index()[:len(sel.Index())-1] {
		t := types.Unalias(cur)
		if p, ok := t.(*types.Pointer); ok {
			t = types.Unalias(p.Elem())
		}
		st, ok := t.Underlying().(*types.Struct)
		if !ok {
			return "", ""
		}
		f := st.Field(idx)
		path += "." + f.Name()
		if !hp.inOnly(f.Pos()) && !g.inTest(f.Pos()) && !hp.hoist[f] {
			if p, ok := types.Unalias(f.Type()).(*types.Pointer); ok {
				if nt := g.hostNamed(hp, p); nt != nil {
					return path, hostName(hp.host, nt.Obj().Name())
				}
			}
		}
		cur = f.Type()
	}
	return "", ""
}

// otherHandlePtr returns, for a pointer to another generated package's
// type that the portable package has as a handle to each host's, the portable
// type's name (pkg.T); or "".
func (g *pkgGen) otherHandlePtr(hp *hostPkg, t types.Type) string {
	p, ok := types.Unalias(t).(*types.Pointer)
	if !ok {
		return ""
	}
	n, ok := types.Unalias(p.Elem()).(*types.Named)
	if !ok || n.Obj().Pkg() == nil || n.Obj().Pkg() == hp.pkg || !token.IsExported(n.Obj().Name()) {
		return ""
	}
	path := n.Obj().Pkg().Path()
	if !g.u.hostDiffers(path, hp.host, n.Obj()) || !g.u.isHandle(path, n.Obj().Name()) {
		return ""
	}
	return g.qual(n.Obj().Pkg()) + n.Obj().Name()
}

// toPortablePtr returns what to wrap a host's value in to store it where the
// portable type holds a pointer t to another generated package's type that
// differs between hosts: a cast for a handle, a copy for data.
func (g *pkgGen) toPortablePtr(hp *hostPkg, t types.Type) (open, close string) {
	if h := g.otherHandlePtr(hp, t); h != "" {
		return "(*" + h + ")(unsafe.Pointer(", "))"
	}
	p, ok := types.Unalias(t).(*types.Pointer)
	if !ok {
		return "", ""
	}
	n, ok := types.Unalias(p.Elem()).(*types.Named)
	if !ok || n.Obj().Pkg() == nil || n.Obj().Pkg() == hp.pkg || !token.IsExported(n.Obj().Name()) {
		return "", ""
	}
	if !g.u.hostDiffers(n.Obj().Pkg().Path(), hp.host, n.Obj()) {
		return "", ""
	}
	return g.qual(n.Obj().Pkg()) + hostName(hp.host, "ToPortable_"+n.Obj().Name()) + "(", ")"
}

// inTest reports whether, while writing the test host's tests, pos is in
// a test file: what tests declare is the test host's own.
func (g *pkgGen) inTest(pos token.Pos) bool {
	return g.testCopy && strings.HasSuffix(fset.Position(pos).Filename, "_test.go")
}

// qual is how the file being written qualifies a name of pkg: "pkg." (as
// it imports it), or nothing for a dot import.
func (g *pkgGen) qual(pkg *types.Package) string {
	switch n := g.importNames[pkg.Path()]; n {
	case ".":
		return ""
	case "", "_":
		return pkg.Name() + "."
	default:
		return n + "."
	}
}

// someHostsDeclare reports whether only some hosts declare name.
func (g *pkgGen) someHostsDeclare(name string) bool {
	n := 0
	for _, hp := range g.hs {
		if _, ok := hp.decls[name]; ok {
			n++
		}
	}
	return n > 0 && n < len(g.hs)
}
