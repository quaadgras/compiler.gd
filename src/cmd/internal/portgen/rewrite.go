type edit struct {
	start, end int
	text       string
}

func applyEdits(src []byte, edits []edit) []byte {
	// (At the same place, insertions come before what replaces text.)
	sort.SliceStable(edits, func(i, j int) bool {
		if edits[i].start != edits[j].start {
			return edits[i].start < edits[j].start
		}
		return edits[i].start == edits[i].end && edits[j].start != edits[j].end
	})
	var out bytes.Buffer
	last := 0
	for _, e := range edits {
		if e.start < last {
			continue // inside an earlier edit
		}
		out.Write(src[last:e.start])
		out.WriteString(e.text)
		last = e.end
	}
	out.Write(src[last:])
	return out.Bytes()
}

var buildLine = regexp.MustCompile(`(?m)^//go:build .*\n|^// \+build .*\n`)

// outName names a host file so that no _GOOS or _GOARCH suffix selects it.
func outName(host, name string) string {
	ext := filepath.Ext(name)
	base := strings.TrimSuffix(name, ext)
	return "zportable_" + host + "_" + strings.ReplaceAll(base, "_", "-") + ext
}

const header = "// Code generated by cmd/portgen from %s; DO NOT EDIT.\n\n//go:build portable && %s\n\n"

// hostOnly reports whether the package-level name, which a host copy of
// another package uses from package path, is a host copy's name there.
func (u *universe) hostOnly(path, host, name string) bool {
	if !u.generate[path] {
		return false
	}
	g := u.load(path)
	g.prepare()
	for _, hp := range g.hs {
		if hp.host == host {
			_, ok := hp.decls[name]
			return ok && !g.dedup[name] && !g.sharedVar[name]
		}
	}
	return false
}

func (g *pkgGen) writeGo(hp *hostPkg, name string) {
	src, err := os.ReadFile(filepath.Join(g.dir, realName(name)))
	if err != nil {
		fatalf("%v", err)
	}
	f := hp.files[name]
	g.importNames = map[string]string{}
	for _, imp := range f.Imports {
		p := strings.Trim(imp.Path.Value, `"`)
		if imp.Name != nil {
			g.importNames[p] = imp.Name.Name
		}
	}
	tf := fset.File(f.Pos())
	off := func(p token.Pos) int { return tf.Offset(p) }
	var edits []edit
	if name != realName(name) {
		// The host part of a split file: without what stays shared.
		edits = g.hostPartEdits(realName(name))
	}
	needUnsafe := false
	extraImports := map[string]string{} // path to name

	ast.Inspect(f, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.Ident:
			obj := hp.info.Defs[n]
			if _, ok := hp.rename[obj]; !ok {
				// An embedded field's name is its type's.
				if u := hp.info.Uses[n]; u != nil {
					obj = u
				}
			}
			if v, ok := obj.(*types.Var); ok && hp.info.Defs[n] == nil && v.Parent() == hp.pkg.Scope() && g.sharedVar[v.Name()] {
				// A use of the one variable the portable package has.
			} else if newName, ok := hp.rename[obj]; ok {
				edits = append(edits, edit{off(n.Pos()), off(n.End()), newName})
			} else if v, ok := obj.(*types.Var); ok && v.IsField() && v.Embedded() && hp.inOnly(v.Pos()) {
				// An embedded field is named for its type.
				if et := g.hostNamed(hp, v.Type()); et != nil && v.Name() == et.Obj().Name() {
					edits = append(edits, edit{off(n.Pos()), off(n.End()), hostName(hp.host, v.Name())})
				}
			}
			// The runtime's own GOOS constant is known in a host file.
			if n.Name == "GOOS" {
				if c, ok := hp.info.Uses[n].(*types.Const); ok && c.Pkg() == hp.pkg {
					edits = append(edits, edit{off(n.Pos()), off(n.End()), fmt.Sprintf("%q", hp.host)})
				}
			}
		case *ast.AssignStmt:
			// A shared struct's field that points to another package's
			// handle holds the portable type's pointer.
			if len(n.Lhs) != len(n.Rhs) {
				break
			}
			for i, l := range n.Lhs {
				sel, ok := l.(*ast.SelectorExpr)
				if !ok {
					continue
				}
				s := hp.info.Selections[sel]
				if s == nil || s.Kind() != types.FieldVal {
					continue
				}
				// (A host struct's field is the host's.)
				hostField := s.Obj().Pkg() == hp.pkg && (hp.inOnly(s.Obj().Pos()) || g.inTest(s.Obj().Pos()))
				if owner := fieldOwnerOf(s); owner != nil && owner.Obj().Pkg() != nil && owner.Obj().Pkg() != hp.pkg && g.u.hostDiffers(owner.Obj().Pkg().Path(), hp.host, owner.Obj()) {
					continue
				}
				if t := g.otherHandlePtr(hp, s.Obj().Type()); t != "" && hostField {
					pkg, name, _ := cutLast(t, ".")
					t = pkg + "." + hostName(hp.host, name)
					needUnsafe = true
					v := n.Rhs[i]
					edits = append(edits, edit{off(v.Pos()), off(v.Pos()), "(*" + t + ")(unsafe.Pointer("})
					edits = append(edits, edit{off(v.End()), off(v.End()), "))"})
				} else if open, close := g.toPortablePtr(hp, s.Obj().Type()); open != "" && !hostField {
					needUnsafe = true
					v := n.Rhs[i]
					edits = append(edits, edit{off(v.Pos()), off(v.Pos()), open})
					edits = append(edits, edit{off(v.End()), off(v.End()), close})
				}
			}
		case *ast.CompositeLit:
			// A shared struct's field that points to a host type holds
			// the portable type's pointer.
			t := types.Unalias(hp.info.Types[n].Type)
			nt, ok := t.(*types.Named)
			if !ok || nt.Obj().Pkg() == nil {
				break
			}
			// (Or another generated package's shared struct, whose
			// fields of other packages' host types are the portable types.)
			other := nt.Obj().Pkg() != hp.pkg
			if other && (!g.u.generate[nt.Obj().Pkg().Path()] || g.u.hostDiffers(nt.Obj().Pkg().Path(), hp.host, nt.Obj())) {
				break
			}
			if !other && (g.hostNamed(hp, nt) != nil || g.inTest(nt.Obj().Pos())) {
				break
			}
			st, ok := nt.Underlying().(*types.Struct)
			if !ok {
				break
			}
			for i, e := range n.Elts {
				var f *types.Var
				v := e
				if kv, ok := e.(*ast.KeyValueExpr); ok {
					v = kv.Value
					if id, ok := kv.Key.(*ast.Ident); ok {
						for fi := range st.Fields() {
							if fi.Name() == id.Name {
								f = fi
							}
						}
					}
				} else if i < st.NumFields() {
					f = st.Field(i)
				}
				if f == nil || !other && hp.inOnly(f.Pos()) {
					continue
				}
				if open, close := g.toPortablePtr(hp, f.Type()); open != "" {
					needUnsafe = true
					edits = append(edits, edit{off(v.Pos()), off(v.Pos()), open})
					edits = append(edits, edit{off(v.End()), off(v.End()), close})
					continue
				}
				if other {
					continue
				}
				// A host value held by value: the portable type's.
				if hn, ok := types.Unalias(f.Type()).(*types.Named); ok && g.hostNamed(hp, hn) != nil && g.canon[hn.Obj().Name()] && token.IsExported(hn.Obj().Name()) && f.Exported() {
					// (Converted as the type's functions do.)
					g.needPortablePtr = true
					edits = append(edits, edit{off(v.Pos()), off(v.Pos()), "*" + hostName(hp.host, "ToPortable_"+hn.Obj().Name()) + "(portablePtr("})
					edits = append(edits, edit{off(v.End()), off(v.End()), "))"})
					continue
				}
				if hn, ok := types.Unalias(f.Type()).(*types.Named); ok && g.hostNamed(hp, hn) != nil && !g.union[hn.Obj().Name()] && !g.canon[hn.Obj().Name()] {
					name := hn.Obj().Name()
					if g.sideBySide(name) {
						edits = append(edits, edit{off(v.Pos()), off(v.Pos()), name + "{" + hp.host + ": "})
						edits = append(edits, edit{off(v.End()), off(v.End()), "}"})
					} else {
						g.needPortableValue = true
						edits = append(edits, edit{off(v.Pos()), off(v.Pos()), "portableValue[" + name + "]("})
						edits = append(edits, edit{off(v.End()), off(v.End()), ")"})
					}
					continue
				}
				if p, ok := types.Unalias(f.Type()).(*types.Pointer); ok {
					if hn := g.hostNamed(hp, p); hn != nil && !g.union[hn.Obj().Name()] {
						needUnsafe = true
						edits = append(edits, edit{off(v.Pos()), off(v.Pos()), "(*" + hn.Obj().Name() + ")(unsafe.Pointer("})
						edits = append(edits, edit{off(v.End()), off(v.End()), "))"})
					}
				}
			}
		case *ast.SelectorExpr:
			if sel := hp.info.Selections[n]; sel != nil && (sel.Kind() == types.MethodVal || sel.Kind() == types.MethodExpr) {
				// Another generated package's method that its host
				// copies declare on a shared type.
				if m, ok := sel.Obj().(*types.Func); ok && m.Pkg() != nil && m.Pkg() != hp.pkg && g.u.hostMethod(m.Pkg().Path(), hp.host, m) {
					edits = append(edits, edit{off(n.Sel.Pos()), off(n.Sel.End()), hostName(hp.host, m.Name())})
				}
			}
			if sel := hp.info.Selections[n]; sel != nil && sel.Kind() == types.FieldVal {
				// Another generated package's embedded host type: the
				// field is named for the host's type.
				// (A shared struct's embedded field is the portable type's.)
				owner := fieldOwnerOf(sel)
				if f := sel.Obj().(*types.Var); f.Embedded() && f.Pkg() != nil && f.Pkg() != hp.pkg && (owner == nil || owner.Obj().Pkg() == nil || g.u.hostDiffers(owner.Obj().Pkg().Path(), hp.host, owner.Obj())) {
					if et, ok := derefNamed(f.Type()); ok && et.Obj().Name() == f.Name() && g.u.hostOnly(et.Obj().Pkg().Path(), hp.host, f.Name()) {
						edits = append(edits, edit{off(n.Sel.Pos()), off(n.Sel.End()), hostName(hp.host, f.Name())})
					}
				}
			}
			if sel := hp.info.Selections[n]; sel != nil && sel.Kind() == types.FieldVal {
				// A shared struct's field of another package's public
				// type: the host's, converted.
				if conv := g.fromPortable(hp, sel); conv != "" && !hp.isLHS(n) && !g.toShared(hp, n) {
					edits = append(edits, edit{off(n.Pos()), off(n.Pos()), conv + "("})
					edits = append(edits, edit{off(n.End()), off(n.End()), ")"})
				}
			}
			if sel := hp.info.Selections[n]; sel != nil && (sel.Kind() == types.FieldVal || sel.Kind() == types.MethodVal) && len(sel.Index()) > 1 {
				// A field or method promoted through a shared struct's
				// embedded pointer to a host type: through the host's.
				if path, t := g.viaHostEmbed(hp, sel); t != "" {
					needUnsafe = true
					edits = append(edits, edit{off(n.X.Pos()), off(n.X.Pos()), "(*" + t + ")(unsafe.Pointer("})
					edits = append(edits, edit{off(n.X.End()), off(n.X.End()), path + "))"})
				}
			}
			if sel := hp.info.Selections[n]; sel != nil && sel.Kind() == types.FieldVal && hp.rename[sel.Obj()] == "" && !hp.hoist[sel.Obj()] && !hp.inOnly(sel.Obj().Pos()) && !g.inTest(sel.Obj().Pos()) {
				// A shared struct's field of a host type holds the host's.
				ft := sel.Obj().Type()
				if a, ok := ft.(*types.Alias); ok && a.Obj().Pkg() == hp.pkg && hp.inOnly(a.Obj().Pos()) && !g.dedup[a.Obj().Name()] {
					needUnsafe = true
					t := hostName(hp.host, a.Obj().Name())
					edits = append(edits, edit{off(n.Pos()), off(n.Pos()), "(*(*" + t + ")(unsafe.Pointer(&"})
					edits = append(edits, edit{off(n.End()), off(n.End()), ")))"})
				} else if nt, ok := types.Unalias(ft).(*types.Named); ok && nt.TypeArgs().Len() > 0 && g.hostTypeString(hp, ft) != g.typeString(hp, ft) {
					// An instance of a generic type of host types
					// (atomic.Pointer[dirInfo]): the host's.
					t := g.hostTypeStringQ(hp, ft, func(p *types.Package) string {
						name := "portable_" + p.Name()
						extraImports[p.Path()] = name
						return name
					})
					needUnsafe = true
					edits = append(edits, edit{off(n.Pos()), off(n.Pos()), "(*(*" + t + ")(unsafe.Pointer(&"})
					edits = append(edits, edit{off(n.End()), off(n.End()), ")))"})
				} else if nt := g.hostNamed(hp, ft); nt != nil && g.canon[nt.Obj().Name()] && token.IsExported(nt.Obj().Name()) && sel.Obj().Exported() && !isPointer(ft) && !hp.isWritten(n) {
					// An exported type's value a shared struct's
					// exported field holds is the portable type's (code
					// outside reads it): the host's copy of it. (An
					// unexported field, like SockaddrInet4.raw, holds
					// the host's.)
					edits = append(edits, edit{off(n.Pos()), off(n.Pos()), "(*" + hostName(hp.host, "FromPortable_"+nt.Obj().Name()) + "(&"})
					edits = append(edits, edit{off(n.End()), off(n.End()), "))"})
				} else if nt := g.hostNamed(hp, ft); nt != nil {
					if g.canon[nt.Obj().Name()] && token.IsExported(nt.Obj().Name()) && sel.Obj().Exported() && !isPointer(ft) {
						g.reportf("%s: %s: host code writes the portable type's %s as the host's", hp.host, relPos(n.Pos()), nt.Obj().Name())
					}
					t := hostName(hp.host, nt.Obj().Name())
					if _, ok := types.Unalias(ft).(*types.Pointer); ok {
						t = "*" + t
					}
					needUnsafe = true
					edits = append(edits, edit{off(n.Pos()), off(n.Pos()), "(*(*" + t + ")(unsafe.Pointer(&"})
					edits = append(edits, edit{off(n.End()), off(n.End()), ")))"})
				}
			}
			x, ok := n.X.(*ast.Ident)
			if !ok {
				break
			}
			pn, ok := hp.info.Uses[x].(*types.PkgName)
			if !ok {
				break
			}
			path := pn.Imported().Path()
			// goos.IsLinux, goos.GOOS and runtime.GOOS are known.
			if path == "internal/goos" {
				if v := goosValue(hp.host, n.Sel.Name); v != "" {
					edits = append(edits, edit{off(n.Pos()), off(n.End()), v})
					return false
				}
			}
			if path == "runtime" && n.Sel.Name == "GOOS" {
				edits = append(edits, edit{off(n.Pos()), off(n.End()), fmt.Sprintf("%q", hp.host)})
				return false
			}
			// Another generated package's host names are its host copy's.
			if g.u.hostOnly(path, hp.host, n.Sel.Name) {
				edits = append(edits, edit{off(n.Sel.Pos()), off(n.Sel.End()), hostName(hp.host, n.Sel.Name)})
			}
			return false
		case *ast.ValueSpec:
			// A package-level variable's value that calls code is
			// computed on its host only: every host copy's
			// initialization runs on every host.
			if gd := hp.parentGenDecl(n); gd == nil || gd.Tok != token.VAR || len(n.Values) == 0 || hp.info.Defs[n.Names[0]] == nil || hp.info.Defs[n.Names[0]].Parent() != hp.pkg.Scope() {
				break
			}
			if !hp.callsCode(n.Values...) || g.testCopy {
				break // (a test copy is only ever on its host)
			}
			var ts, zeros []string
			for _, id := range n.Names {
				t := g.hostTypeString(hp, hp.info.Defs[id].Type())
				ts = append(ts, t)
				zeros = append(zeros, "*new("+t+")")
			}
			first, last := n.Values[0], n.Values[len(n.Values)-1]
			res := strings.Join(ts, ", ")
			if len(ts) > 1 {
				res = "(" + res + ")"
			}
			edits = append(edits, edit{off(first.Pos()), off(first.Pos()), fmt.Sprintf("func() %s {\nif portablehost != portable%s {\nreturn %s\n}\nreturn ", res, title(hp.host), strings.Join(zeros, ", "))})
			edits = append(edits, edit{off(last.End()), off(last.End()), "\n}()"})
		case *ast.FuncDecl:
			// The host's init functions: the package's init calls them
			// on the host.
			// An example of what only some hosts declare is, in the
			// test host's tests, the package's: portable has no such name.
			if g.testCopy && n.Recv == nil && strings.HasPrefix(n.Name.Name, "Example") {
				if rest := strings.TrimPrefix(n.Name.Name, "Example"); rest != "" && rest[0] != '_' {
					ident, _, _ := strings.Cut(rest, "_")
					if g.someHostsDeclare(ident) {
						newName := "Example_" + strings.ToLower(rest[:1]) + rest[1:]
						edits = append(edits, edit{off(n.Name.Pos()), off(n.Name.End()), newName})
						break
					}
				}
			}
			if n.Recv == nil && n.Name.Name == "init" && n.Body != nil && !g.testCopy {
				name := fmt.Sprintf("%s_init%d", hp.host, len(hp.inits))
				hp.inits = append(hp.inits, name)
				edits = append(edits, edit{off(n.Name.Pos()), off(n.Name.End()), name})
				break
			}
			// A renamed function without a body (that the host's
			// assembly does not define) still links to its name, which
			// another package pushes.
			fn, ok := hp.info.Defs[n.Name].(*types.Func)
			if !ok || n.Body != nil || n.Recv != nil || hp.rename[fn] == "" || hp.linkname(fn) != "" || g.asmDefinesFunc(hp, fn.Name()) {
				// (A one-argument linkname is rewritten below.)
				break
			}
			needUnsafe = true
			target := fn.Name()
			if g.splitPull(target) {
				target = hp.rename[fn]
			}
			edits = append(edits, edit{off(n.Pos()), off(n.Pos()), fmt.Sprintf("//go:linkname %s %s.%s\n", hp.rename[fn], g.path, target)})
		case *ast.CallExpr:
			// A shared function takes the portable type where the host file
			// passes its own.
			id, ok := n.Fun.(*ast.Ident)
			if !ok {
				break
			}
			// (Or a shared variable of a function type: a test hook.)
			fn := hp.info.Uses[id]
			switch fn.(type) {
			case *types.Func:
			case *types.Var:
				if _, ok := fn.Type().Underlying().(*types.Signature); !ok || fn.Parent() != hp.pkg.Scope() {
					fn = nil
				}
			default:
				fn = nil
			}
			if fn == nil || fn.Pkg() != hp.pkg || hp.inOnly(fn.Pos()) || g.inTest(fn.Pos()) {
				break
			}
			sig, _ := fn.Type().Underlying().(*types.Signature)
			for i, arg := range n.Args {
				t := hp.info.Types[arg].Type
				nt := g.hostNamed(hp, t)
				if nt == nil {
					continue
				}
				// (A parameter of an interface type takes the host's
				// value as it is: KeepAlive(attr).)
				if sig != nil && sig.Params().Len() > 0 {
					pi := min(i, sig.Params().Len()-1)
					pt := sig.Params().At(pi).Type()
					if sig.Variadic() && pi == sig.Params().Len()-1 && !n.Ellipsis.IsValid() {
						if s, ok := pt.(*types.Slice); ok {
							pt = s.Elem()
						}
					}
					if types.IsInterface(pt) {
						continue
					}
				}
				if g.canon[nt.Obj().Name()] && hp != g.first() {
					g.reportf("%s: %s: cannot pass a %s to a shared function", hp.host, relPos(arg.Pos()), nt.Obj().Name())
					continue
				}
				if _, isPtr := types.Unalias(t).(*types.Pointer); !isPtr {
					g.reportf("%s: %s: cannot pass a %s by value to a shared function", hp.host, relPos(arg.Pos()), nt.Obj().Name())
					continue
				}
				needUnsafe = true
				edits = append(edits, edit{off(arg.Pos()), off(arg.Pos()), "(*" + nt.Obj().Name() + ")(unsafe.Pointer("})
				edits = append(edits, edit{off(arg.End()), off(arg.End()), "))"})
			}
		case *ast.StructType:
			// Fields hoisted into the portable type leave the host's.
			for _, fl := range n.Fields.List {
				if len(fl.Names) == 1 && hp.hoist[hp.info.Defs[fl.Names[0]]] {
					edits = append(edits, deleteNode(off, fl, fl.Doc, fl.Comment))
				}
			}
		case *ast.GenDecl:
			// Types and variables the portable file declares for every host.
			if n.Tok != token.TYPE && n.Tok != token.VAR {
				break
			}
			var keep int
			var dels []edit
			for _, s := range n.Specs {
				switch s := s.(type) {
				case *ast.TypeSpec:
					if hp.drop[hp.info.Defs[s.Name]] {
						dels = append(dels, deleteNode(off, s, s.Doc, s.Comment))
						continue
					}
				case *ast.ValueSpec:
					if len(s.Names) == 1 && hp.drop[hp.info.Defs[s.Names[0]]] {
						dels = append(dels, deleteNode(off, s, s.Doc, s.Comment))
						continue
					}
				}
				keep++
			}
			if keep == 0 && len(dels) > 0 {
				edits = append(edits, deleteNode(off, n, n.Doc, nil))
				return false
			}
			edits = append(edits, dels...)
		}
		return true
	})

	for _, path := range slices.Sorted(maps.Keys(extraImports)) {
		edits = append(edits, edit{off(f.Name.End()), off(f.Name.End()), fmt.Sprintf("\n\nimport %s %q", extraImports[path], strings.TrimPrefix(path, "vendor/"))})
	}
	if needUnsafe && !slices.ContainsFunc(f.Imports, func(s *ast.ImportSpec) bool {
		return s.Path.Value == `"unsafe"` && (s.Name == nil || s.Name.Name == "unsafe")
	}) {
		edits = append(edits, edit{off(f.Name.End()), off(f.Name.End()), "\n\nimport \"unsafe\""})
	}

	// Imports of packages some host does not build: the host's variant.
	for _, imp := range f.Imports {
		p := strings.Trim(imp.Path.Value, `"`)
		if p == "C" || p == "unsafe" || strings.Contains(strings.Split(p, "/")[0], ".") {
			continue
		}
		if g.u.variant(p, hp.host) {
			text := fmt.Sprintf("%q", "portable/"+hp.host+"/"+p)
			if imp.Name == nil {
				text = filepath.Base(p) + " " + text
			}
			edits = append(edits, edit{off(imp.Path.Pos()), off(imp.Path.End()), text})
		}
	}
	// goos and runtime may now be unused.
	end := 0
	for _, d := range f.Decls {
		if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.IMPORT {
			end = max(end, off(gd.End()))
		}
	}
	for _, imp := range f.Imports {
		switch strings.Trim(imp.Path.Value, `"`) {
		case "internal/goos":
			edits = append(edits, edit{end, end, "\n\nvar _ = goos.GOOS"})
		case "runtime":
			if imp.Name == nil || imp.Name.Name != "_" && imp.Name.Name != "." {
				name := "runtime"
				if imp.Name != nil {
					name = imp.Name.Name
				}
				edits = append(edits, edit{end, end, "\n\nvar _ = " + name + ".GOARCH"})
			}
		}
	}

	// Directives: //go:linkname local [target].
	byName := map[string]string{}
	for obj, n := range hp.rename {
		if obj.Parent() == hp.pkg.Scope() {
			byName[obj.Name()] = n
		}
	}
	for _, cg := range f.Comments {
		for _, c := range cg.List {
			// //go:cgo_import_dynamic pkg.local remote "lib": the host's
			// local name.
			if fs := strings.Fields(c.Text); len(fs) >= 2 && fs[0] == "//go:cgo_import_dynamic" {
				if pkg, name, ok := cutLast(fs[1], "."); ok && pkg == g.path {
					if n, ok := byName[name]; ok {
						fs[1] = pkg + "." + n
						edits = append(edits, edit{off(c.Pos()), off(c.End()), strings.Join(fs, " ")})
					}
				}
				continue
			}
			if !strings.HasPrefix(c.Text, "//go:linkname ") && !strings.HasPrefix(c.Text, "//go:linknamestd ") {
				continue
			}
			fs := strings.Fields(c.Text)
			if o := hp.pkg.Scope().Lookup(fs[1]); o != nil && hp.drop[o] {
				// The portable file declares it, with the directive.
				edits = append(edits, edit{off(c.Pos()), off(c.End()), ""})
				continue
			}
			if newName, ok := byName[fs[1]]; ok {
				// A renamed function without a body that another
				// package pushes keeps its name.
				if fn, ok := hp.pkg.Scope().Lookup(fs[1]).(*types.Func); ok && len(fs) == 2 && !hp.hasBody(fn) && !g.asmDefinesFunc(hp, fn.Name()) {
					fs = append(fs, g.path+"."+fs[1])
				}
				fs[1] = newName
			}
			if len(fs) == 3 && g.splitPushes[fs[2]] {
				pkg, name, _ := cutLast(fs[2], ".")
				fs[2] = pkg + "." + hostName(hp.host, name)
				edits = append(edits, edit{off(c.Pos()), off(c.End()), strings.Join(fs, " ")})
				continue
			}
			if len(fs) == 3 && g.pushes[fs[2]] != nil {
				edits = append(edits, edit{off(c.Pos()), off(c.End()), "// (portgen: zportable_dispatch pushes " + fs[2] + ")"})
				continue
			}
			if len(fs) == 3 && !g.testCopy {
				// A pull of another generated package's host name is
				// of its host copy. (A test's is of the portable package's,
				// which its package marks.)
				// (A function there without a body keeps its name: that
				// is what is pushed.)
				if pkg, sym, ok := cutLast(fs[2], "."); ok && pkg != g.path && g.u.hostOnly(pkg, hp.host, sym) && g.u.hostHasBody(pkg, hp.host, sym) {
					fs[2] = pkg + "." + hostName(hp.host, sym)
				}
			}
			edits = append(edits, edit{off(c.Pos()), off(c.End()), strings.Join(fs, " ")})
		}
	}

	name = realName(name)
	if g.testCopy {
		g.testOut[name] = g.finishGo(src, edits, name, name)
		return
	}
	g.outputs[outName(hp.host, name)] = g.finishGo(src, edits, name, outName(hp.host, name))
}

// writeTests writes the tests of the test host hp, in-package and
// external, as host copies: a test binary of a GOOS=portable package has one
// host's tests (it runs on that host), of the package as portable builds it.
func (g *pkgGen) writeTests(hp *hostPkg) {
	if !hp.tests {
		return // they do not type-check: leave them out as before
	}
	g.testCopy = true
	defer func() { g.testCopy = false }()
	g.testOut = map[string][]byte{}
	for _, name := range hp.bp.TestGoFiles {
		g.writeGo(hp, name)
	}
	if hp.xinfo != nil && len(hp.bp.XTestGoFiles) > 0 {
		info, pkg, files, parents := hp.info, hp.pkg, hp.files, hp.parents
		hp.info, hp.pkg, hp.files, hp.parents = hp.xinfo, hp.xpkg, hp.xfiles, nil
		for _, name := range hp.bp.XTestGoFiles {
			g.writeGo(hp, name)
		}
		hp.info, hp.pkg, hp.files, hp.parents = info, pkg, files, parents
	}
}

// testName names the test host's copy of a test file only some hosts
// build: as a test file no _GOOS suffix selects.
func testName(host, name string) string {
	base := strings.TrimSuffix(name, "_test.go")
	return "zportable_" + host + "_" + strings.ReplaceAll(base, "_", "-") + "_test.go"
}

// finishGo applies the edits to src, the file name, and returns the
// generated file: with the generated header in place of the build line,
// and line directives so that what it compiles to has name's positions.
func (g *pkgGen) finishGo(src []byte, edits []edit, name, out string) []byte {
	for _, loc := range buildLine.FindAllIndex(src, -1) {
		edits = append(edits, edit{loc[0], loc[1], ""})
	}
	file := filepath.Join(g.dir, name)
	b := applyEditsLines(src, edits, file)
	b = append([]byte(fmt.Sprintf(header, name, *arch)+"/*line "+file+":1:1*/"), b...)
	b = dropUnusedImports(b)
	if _, err := parser.ParseFile(token.NewFileSet(), out, b, parser.SkipObjectResolution); err != nil {
		g.reportf("%s: %v", out, err)
	}
	return b
}

// applyEditsLines is applyEdits, with a line directive after each edit
// that adds or removes lines, so that what follows keeps its position in
// the file name.
func applyEditsLines(src []byte, edits []edit, name string) []byte {
	sort.SliceStable(edits, func(i, j int) bool {
		if edits[i].start != edits[j].start {
			return edits[i].start < edits[j].start
		}
		return edits[i].start == edits[i].end && edits[j].start != edits[j].end
	})
	var out bytes.Buffer
	last := 0
	line, lineStart, counted := 1, 0, 0
	pos := func(off int) (int, int) {
		for ; counted < off; counted++ {
			if src[counted] == '\n' {
				line++
				lineStart = counted + 1
			}
		}
		return line, off - lineStart + 1
	}
	for _, e := range edits {
		if e.start < last {
			continue // inside an earlier edit
		}
		out.Write(src[last:e.start])
		out.WriteString(e.text)
		last = e.end
		if strings.Contains(e.text, "\n") || bytes.Contains(src[e.start:e.end], []byte("\n")) {
			l, c := pos(e.end)
			fmt.Fprintf(&out, "/*line %s:%d:%d*/", name, l, c)
		}
	}
	out.Write(src[last:])
	return out.Bytes()
}

// hostHasBody reports whether the host copy of package path declares
// name with a body (or as a variable): one other packages link to by
// its host name.
func (u *universe) hostHasBody(path, host, name string) bool {
	q := u.load(path)
	q.prepare()
	for _, hp := range q.hs {
		if hp.host != host {
			continue
		}
		fn, ok := hp.decls[name].(*types.Func)
		if !ok {
			return true
		}
		return hp.hasBody(fn) || q.asmDefinesFunc(hp, name)
	}
	return false
}

// derefNamed returns the named type t is or points to.
func derefNamed(t types.Type) (*types.Named, bool) {
	t = types.Unalias(t)
	if p, ok := t.(*types.Pointer); ok {
		t = types.Unalias(p.Elem())
	}
	n, ok := t.(*types.Named)
	return n, ok && n.Obj().Pkg() != nil
}

// hostMethod reports whether m, a method of generated package path, is
// one that path's host copies declare on a shared type.
func (u *universe) hostMethod(path, host string, m *types.Func) bool {
	if !u.generate[path] {
		return false
	}
	q := u.load(path)
	q.prepare()
	for _, hp := range q.hs {
		if hp.host != host {
			continue
		}
		file := fileNameAnyParse(m.Pos())
		if !hp.only[file] {
			return false
		}
		recv := m.Signature().Recv()
		if recv == nil {
			return false
		}
		t := types.Unalias(recv.Type())
		if p, ok := t.(*types.Pointer); ok {
			t = types.Unalias(p.Elem())
		}
		n, ok := t.(*types.Named)
		if !ok {
			return false
		}
		o := hp.pkg.Scope().Lookup(n.Obj().Name())
		return o != nil && (!hp.inOnly(o.Pos()) || q.dedup[o.Name()])
	}
	return false
}

// fromPortable returns the function that converts the value of the shared
// struct field sel, of another package's public type that differs
// between hosts (os.ProcAttr.Sys, a *syscall.SysProcAttr), to the
// host's type, or "".
func (g *pkgGen) fromPortable(hp *hostPkg, sel *types.Selection) string {
	f := sel.Obj().(*types.Var)
	if g.inTest(f.Pos()) {
		return "" // a test's struct's field is the test host's
	}
	if owner := fieldOwnerOf(sel); f.Pkg() == hp.pkg && hp.inOnly(f.Pos()) && (owner == nil || !g.dedup[owner.Obj().Name()]) {
		return "" // a host struct's field is the host's
	}
	if owner := fieldOwnerOf(sel); owner != nil && owner.Obj().Pkg() != nil && owner.Obj().Pkg() != hp.pkg && g.u.hostDiffers(owner.Obj().Pkg().Path(), hp.host, owner.Obj()) {
		return "" // so is another package's host struct's
	}
	p, ok := types.Unalias(f.Type()).(*types.Pointer)
	if !ok {
		return ""
	}
	n, ok := types.Unalias(p.Elem()).(*types.Named)
	if !ok || n.Obj().Pkg() == nil || n.Obj().Pkg() == hp.pkg || !token.IsExported(n.Obj().Name()) {
		return ""
	}
	if !g.u.hostDiffers(n.Obj().Pkg().Path(), hp.host, n.Obj()) {
		return ""
	}
	g.u.needFromPortable(n.Obj().Pkg().Path(), n.Obj().Name())
	return g.qual(n.Obj().Pkg()) + hostName(hp.host, "FromPortable_"+n.Obj().Name())
}

// toShared reports whether e is the value of a field in a composite
// literal of a type that is not a host's: it stays the portable value.
func (g *pkgGen) toShared(hp *hostPkg, e ast.Expr) bool {
	hp.useType(e) // builds parents
	if call, ok := hp.parents[e].(*ast.CallExpr); ok && call.Fun != e {
		// An argument of a function that takes the portable type: one of
		// a package with no host copies, or a shared one.
		var fn types.Object
		switch f := ast.Unparen(call.Fun).(type) {
		case *ast.Ident:
			fn = hp.info.Uses[f]
		case *ast.SelectorExpr:
			if hp.info.Selections[f] == nil {
				fn = hp.info.Uses[f.Sel]
			}
		}
		fn, ok := fn.(*types.Func)
		if !ok || fn.Pkg() == nil {
			return false
		}
		if fn.Pkg() == hp.pkg {
			return !hp.inOnly(fn.Pos())
		}
		// (Another generated package's host function takes the
		// host's.)
		return !g.u.hostOnly(fn.Pkg().Path(), hp.host, fn.Name()) && !g.u.hostDiffers(fn.Pkg().Path(), hp.host, fn)
	}
	kv, ok := hp.parents[e].(*ast.KeyValueExpr)
	if !ok || kv.Value != e {
		return false
	}
	lit, ok := hp.parents[kv].(*ast.CompositeLit)
	if !ok {
		return false
	}
	t := types.Unalias(hp.info.Types[lit].Type)
	if p, ok := t.(*types.Pointer); ok {
		t = types.Unalias(p.Elem())
	}
	n, ok := t.(*types.Named)
	if !ok || n.Obj().Pkg() == nil {
		return false
	}
	if n.Obj().Pkg() == hp.pkg {
		return g.hostNamed(hp, n) == nil
	}
	return !g.u.hostDiffers(n.Obj().Pkg().Path(), hp.host, n.Obj())
}

// isWritten reports whether e, or a field or element of it, is assigned
// to or has its address taken.
func (hp *hostPkg) isWritten(e ast.Expr) bool {
	for {
		if hp.isLHS(e) {
			return true
		}
		switch p := hp.parents[e].(type) {
		case *ast.SelectorExpr:
			if p.X != e {
				return false
			}
			if s := hp.info.Selections[p]; s == nil || s.Kind() != types.FieldVal {
				// (A method: one of a pointer receiver may write.)
				return s != nil && isPointer(s.Obj().Type().(*types.Signature).Recv().Type())
			}
			e = p
		case *ast.IndexExpr:
			if p.X != e {
				return false
			}
			e = p
		case *ast.ParenExpr:
			e = p
		default:
			return false
		}
	}
}

func isPointer(t types.Type) bool {
	_, ok := types.Unalias(t).(*types.Pointer)
	return ok
}

// isLHS reports whether e is assigned to or has its address taken.
func (hp *hostPkg) isLHS(e ast.Expr) bool {
	hp.useType(e) // builds parents
	switch p := hp.parents[e].(type) {
	case *ast.AssignStmt:
		for _, l := range p.Lhs {
			if l == e {
				return true
			}
		}
	case *ast.UnaryExpr:
		return p.Op == token.AND
	case *ast.IncDecStmt:
		return true
	}
	return false
}

// parentGenDecl returns the declaration a value spec is in.
func (hp *hostPkg) parentGenDecl(n *ast.ValueSpec) *ast.GenDecl {
	hp.useType(nil) // builds parents
	gd, _ := hp.parents[n].(*ast.GenDecl)
	return gd
}

// callsCode reports whether the expressions call a function (not a
// conversion or a builtin): a value computed at run time.
func (hp *hostPkg) callsCode(es ...ast.Expr) bool {
	found := false
	for _, e := range es {
		ast.Inspect(e, func(n ast.Node) bool {
			if _, ok := n.(*ast.FuncLit); ok {
				return false // only called if something calls it
			}
			c, ok := n.(*ast.CallExpr)
			if !ok || found {
				return !found
			}
			if tv, ok := hp.info.Types[c.Fun]; ok && (tv.IsType() || tv.IsBuiltin()) {
				return true
			}
			found = true
			return false
		})
	}
	return found
}

// deleteNode deletes n with its comments.
func deleteNode(off func(token.Pos) int, n ast.Node, doc, comment *ast.CommentGroup) edit {
	start := off(n.Pos())
	if doc != nil {
		start = off(doc.Pos())
	}
	end := off(n.End())
	if comment != nil {
		end = max(end, off(comment.End()))
	}
	return edit{start, end, ""}
}

func goosValue(host, name string) string {
	if name == "GOOS" {
		return fmt.Sprintf("%q", host)
	}
	if strings.HasPrefix(name, "Is") && name != "IsUnix" {
		if strings.EqualFold(name[2:], host) {
			return "1"
		}
		return "0"
	}
	return ""
}

var (
	asmSym     = regexp.MustCompile(`(runtime)?·([A-Za-z_][A-Za-z0-9_]*)`)
	asmTextABI = regexp.MustCompile(`TEXT\s+(?:runtime)?·([A-Za-z_][A-Za-z0-9_]*)(<[A-Za-z0-9]+>)?`)
	asmIdent   = regexp.MustCompile(`\b[A-Za-z_][A-Za-z0-9_]*\b`)
)

func (g *pkgGen) writeAsm(hp *hostPkg, name string) {
	src, err := os.ReadFile(filepath.Join(g.dir, name))
	if err != nil {
		fatalf("%v", err)
	}
	funcs := map[string]string{}
	typeNames := map[string]string{}
	consts := map[string]string{}
	for obj, n := range hp.rename {
		if obj.Parent() != hp.pkg.Scope() {
			continue
		}
		switch obj.(type) {
		case *types.Func, *types.Var:
			funcs[obj.Name()] = n
		case *types.TypeName:
			typeNames[obj.Name()] = n
		case *types.Const:
			consts[obj.Name()] = n
		}
	}
	// Functions only assembly declares are the host's too, and so are
	// the bodies of functions shared files declare: an assembly
	// function dispatches to them. (Calls of those still call the
	// dispatch function: runtime·settls is the portable package's own.)
	dispatched := map[string]bool{}
	for _, m := range asmTextABI.FindAllSubmatch(src, -1) {
		s := string(m[1])
		if _, ok := funcs[s]; ok {
			continue
		}
		obj := hp.pkg.Scope().Lookup(s)
		if obj == nil {
			funcs[s] = hostName(hp.host, s)
		} else if !hp.inOnly(obj.Pos()) {
			funcs[s] = hostName(hp.host, s)
			dispatched[s] = true
			if g.asmDispatch[s] == nil {
				g.asmDispatch[s] = map[string]string{}
			}
			g.asmDispatch[s][hp.host] = string(m[2])
		}
	}
	for t, by := range g.pushes {
		if fn := by[hp.host]; fn != nil {
			pkg, sym, _ := cutLast(t, ".")
			asmName := strings.ReplaceAll(pkg, "/", "∕") + "·" + sym
			src = bytes.ReplaceAll(src, []byte(asmName), []byte("·"+hp.rename[fn]))
		}
	}
	out := asmSym.ReplaceAllFunc(src, func(b []byte) []byte {
		m := asmSym.FindSubmatch(b)
		if len(m[1]) > 0 && g.path != "runtime" {
			// The runtime's host names.
			if g.u.hostOnly("runtime", hp.host, string(m[2])) {
				return []byte("runtime·" + hostName(hp.host, string(m[2])))
			}
			return b
		}
		if n, ok := funcs[string(m[2])]; ok {
			return []byte(string(m[1]) + "·" + n)
		}
		return b
	})
	// Undo that for calls of dispatched functions: only their TEXT is
	// the host's.
	for s := range dispatched {
		n := hostName(hp.host, s)
		lines := strings.Split(string(out), "\n")
		for i, l := range lines {
			if !strings.Contains(l, "·"+n) || strings.HasPrefix(strings.TrimSpace(l), "TEXT") {
				continue
			}
			lines[i] = strings.ReplaceAll(l, "·"+n, "·"+s)
		}
		out = []byte(strings.Join(lines, "\n"))
	}
	// go_asm.h names: T__field, T__size, const_NAME.
	out = asmIdent.ReplaceAllFunc(out, func(b []byte) []byte {
		s := string(b)
		if c, ok := strings.CutPrefix(s, "const_"); ok {
			if n, ok := consts[c]; ok {
				return []byte("const_" + n)
			}
		}
		// T_field and T__size.
		for i := 0; i < len(s); i++ {
			if s[i] == '_' {
				if n, ok := typeNames[s[:i]]; ok {
					return []byte(n + s[i:])
				}
			}
		}
		return b
	})
	out = buildLine.ReplaceAll(out, nil)
	// (GOOS_portable stays defined: the host's assembly may do what only
	// a GOOS=portable program needs.)
	out = append([]byte(fmt.Sprintf(header, name, *arch)+"#define GOOS_"+hp.host+"\n"), out...)
	g.outputs[outName(hp.host, name)] = out
}

// useType returns the type an untyped constant takes where e uses it:
// the type of the smallest enclosing expression that has one.
func (hp *hostPkg) useType(e ast.Expr) types.Type {
	if hp.parents == nil {
		hp.parents = map[ast.Node]ast.Node{}
		for _, f := range hp.files {
			var stack []ast.Node
			ast.Inspect(f, func(n ast.Node) bool {
				if n == nil {
					stack = stack[:len(stack)-1]
					return true
				}
				if len(stack) > 0 {
					hp.parents[n] = stack[len(stack)-1]
				}
				stack = append(stack, n)
				return true
			})
		}
	}
	var n ast.Node = e
	for n != nil {
		if x, ok := n.(ast.Expr); ok {
			if tv, ok := hp.info.Types[x]; ok && tv.Type != nil {
				if b, ok := tv.Type.(*types.Basic); !ok || b.Info()&types.IsUntyped == 0 {
					return tv.Type
				}
			}
		}
		switch p := hp.parents[n].(type) {
		case *ast.BinaryExpr, *ast.ParenExpr, *ast.UnaryExpr:
			n = p
		case *ast.CallExpr:
			// A conversion T(c), or an argument.
			if tv, ok := hp.info.Types[p.Fun]; ok && tv.IsType() {
				return tv.Type
			}
			if sig, ok := hp.info.Types[p.Fun].Type.(*types.Signature); ok {
				for i, a := range p.Args {
					if a == n && i < sig.Params().Len() {
						return sig.Params().At(i).Type()
					}
				}
			}
			return nil
		case *ast.ValueSpec:
			if p.Type != nil {
				return hp.info.Types[p.Type].Type
			}
			return nil
		default:
			return nil
		}
	}
	return nil
}

// collect adds the package's files under GOOS=portable to res: its generated
// files, its split files' shared parts in their place, and the tests
// that do not build for portable.
func (g *pkgGen) collect(res *Result) {
	// A package no host builds has nothing to generate.
	none := true
	for _, hp := range g.hs {
		none = none && hp.pkg.Name() == ""
	}
	if none {
		return
	}
	for n, b := range g.outputs {
		res.Files[filepath.Join(g.dir, n)] = b
	}
	for n, b := range g.sharedOut {
		res.Files[filepath.Join(g.dir, n)] = b
	}
	if g.testOut != nil {
		// The test host's tests: those every host builds in their
		// place, the others as new files.
		for name, b := range g.testOut {
			if g.allBuildTest(name) {
				res.Files[filepath.Join(g.dir, name)] = b
			} else {
				res.Files[filepath.Join(g.dir, testName(g.testHost, name))] = b
			}
		}
		return
	}
	for name, off := range g.testOff {
		if off {
			res.Files[filepath.Join(g.dir, name)] = nil
		}
	}
	for name, off := range g.xoff {
		if off {
			res.Files[filepath.Join(g.dir, name)] = nil
		}
	}
}

