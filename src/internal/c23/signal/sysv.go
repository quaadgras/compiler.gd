// killpg, psiginfo, and the System V signal functions: sighold, sigrelse,
// sigignore, sigpause and sigset.

// Killpg is killpg: sig is sent to the children of the program (that
// have not ended) in process group pgrp, and to the program's own
// process if it is its group (pgrp 0 is). ESRCH if no process is in the
// group, EINVAL for a negative pgrp.
func Killpg(pgrp, sig int32) int32 {
	if pgrp < 0 || sig < 0 || sig >= c23.Nsig {
		c23.SetErrno(c23.EINVAL)
		return -1
	}
	own := getpgrp()
	if pgrp == 0 {
		pgrp = own
	}
	c23.ChildMu.Lock()
	var cs []*c23.Child
	for _, c := range c23.Children {
		if !c.Done {
			cs = append(cs, c)
		}
	}
	c23.ChildMu.Unlock()
	found := false
	for _, c := range cs {
		if pgidOf(c.Pid) != pgrp {
			continue
		}
		found = true
		switch {
		case sig == c23.SIGKILL:
			c.Cmd.Process.Kill()
		case sig != 0:
			if s := sysSignal(sig); s != nil {
				c.Cmd.Process.Signal(s)
			}
		}
	}
	if pgrp == own {
		return killSelf(sig)
	}
	if !found {
		c23.SetErrno(c23.ESRCH)
		return -1
	}
	return 0
}

// The text psiginfo gives a signal's si_code, glibc's.
var siCodeText = map[int32]string{
	SI_USER:       "Signal sent by kill()",
	SI_QUEUE:      "Signal sent by sigqueue()",
	-2:            "Signal generated by the expiration of a timer", // SI_TIMER
	c23.SI_TKILL:  "Signal sent by tkill()",
	c23.SI_KERNEL: "Signal sent by the kernel",
}

// Psiginfo is psiginfo: "message: description (what sent it pid uid)"
// on standard error (fd 2), as glibc's for a signal a process sent, or
// "(what sent it)" for another.
func Psiginfo(info, message c23.Ptr) {
	sig := int32(c23.Load32(info))
	code := int32(c23.Load32(c23.Add(info, 8)))
	msg := c23.Strsignal(sig)
	text, ok := siCodeText[code]
	if !ok {
		text = "Unknown signal code " + strconv.Itoa(int(code))
	}
	switch code {
	case SI_USER, SI_QUEUE, c23.SI_TKILL:
		pid := int32(c23.Load32(c23.Add(info, 12)))
		uid := c23.Load32(c23.Add(info, 16))
		msg += " (" + text + " " + strconv.Itoa(int(pid)) + " " + strconv.FormatUint(uint64(uid), 10) + ")\n"
	default:
		msg += " (" + text + ")\n"
	}
	if c23.Addr(message) != 0 && c23.Load8(message) != 0 {
		msg = c23.GoString(message) + ": " + msg
	}
	if f := c23.FdOS(2); f != nil {
		f.Write([]byte(msg))
	}
}

// sigMask changes the calling thread's mask as sigprocmask(how, {sig})
// does, and reports whether sig was blocked.
func sigMask(how, sig int32) (bool, int32) {
	if !sigValid(sig) {
		return false, -1
	}
	t := c23.SigSelf()
	c23.SigMu.Lock()
	was := t.Mask&c23.SigBit(sig) != 0
	if how == SIG_BLOCK {
		t.Mask |= c23.SigBit(sig)
	} else {
		t.Mask &^= c23.SigBit(sig)
	}
	t.Mask &^= c23.SigUnblockable
	c23.SigMu.Unlock()
	t.DeliverPending()
	return was, 0
}

// Sighold is sighold: sig is added to the calling thread's mask.
func Sighold(sig int32) int32 {
	_, r := sigMask(SIG_BLOCK, sig)
	return r
}

// Sigrelse is sigrelse: sig is removed from the calling thread's mask.
func Sigrelse(sig int32) int32 {
	_, r := sigMask(SIG_UNBLOCK, sig)
	return r
}

// Sigignore is sigignore: sig's disposition becomes SIG_IGN.
func Sigignore(sig int32) int32 {
	if !sigValid(sig) {
		return -1
	}
	if sig == c23.SIGKILL || sig == c23.SIGSTOP {
		c23.SetErrno(c23.EINVAL)
		return -1
	}
	sigSet(sig, c23.SigAction{Handler: c23.FromInt(c23.SigIgn)}, true)
	return 0
}

// Sigpause is XSI's sigpause, as glibc's: it waits, as sigsuspend, with
// sig removed from the calling thread's mask. It returns -1 with errno
// EINTR.
func Sigpause(sig int32) int32 {
	if !sigValid(sig) {
		return -1
	}
	t := c23.SigSelf()
	c23.SigMu.Lock()
	m := t.Mask &^ c23.SigBit(sig)
	c23.SigMu.Unlock()
	c23.Suspend(m)
	c23.SetErrno(c23.EINTR)
	return -1
}

// sigHold is SIG_HOLD.
const sigHold = 2

// Sigset is sigset: SIG_HOLD adds sig to the calling thread's mask;
// another disposition becomes sig's action (with an empty mask and no
// flags) and sig is removed from the mask. It returns SIG_HOLD if sig
// was blocked, its previous disposition if not, or SIG_ERR.
func Sigset(sig int32, disp c23.Ptr) c23.Ptr {
	sigErr := c23.FromInt(^uintptr(0))
	if !sigValid(sig) {
		return sigErr
	}
	if sig == c23.SIGKILL || sig == c23.SIGSTOP {
		c23.SetErrno(c23.EINVAL)
		return sigErr
	}
	var old c23.SigAction
	how := int32(SIG_UNBLOCK)
	if c23.Addr(disp) == sigHold {
		how = SIG_BLOCK
		old = sigSet(sig, c23.SigAction{}, false)
	} else {
		if h := c23.Addr(disp); h != c23.SigDfl && h != c23.SigIgn {
			c23.FuncOf[func(int32)](disp)
		}
		old = sigSet(sig, c23.SigAction{Handler: disp}, true)
	}
	if was, _ := sigMask(how, sig); was {
		return c23.FromInt(sigHold)
	}
	return old.Handler
}
